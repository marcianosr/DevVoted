const POKEMON = [...KANTO, ...JOHTO] as const;

const FNV_OFFSET_BASIS = 0x811c9dc5;
const FNV_PRIME = 0x01000193;
const NUMBER_SPAN = 10_000;

const fnv1a = (text: string): number => {
	let hash = FNV_OFFSET_BASIS;
	for (const char of text) {
		hash ^= char.codePointAt(0) ?? 0;
		hash = Math.imul(hash, FNV_PRIME) >>> 0;
	}
	return hash;
};

const pick = <Item>(items: readonly Item[], seed: string): Item =>
	items[fnv1a(seed) % items.length];

export const guestNameOf = (userId: string): string =>
	[
		pick(ADJECTIVES, `${userId}/adjective`),
		pick(POKEMON, `${userId}/pokemon`),
		fnv1a(`${userId}/number`) % NUMBER_SPAN,
	].join("");
